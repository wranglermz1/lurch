//! Recovers the traversal animations' root motion from recordings and prints it as
//! src/sim/rootmotion.rs: for each traversal type seen, the root's offset from the ledge point
//! by animation cycle, along the traversal's forward, its left and up.
//!
//!   cargo run --release --bin rootmotion traces/*.ltr > src/sim/rootmotion.rs
use std::collections::BTreeMap;

use lurch::ltr::{f32_at, open, u32_at, vec3_at};
use lurch::sim::mantle::{JUMP_OFF, MOVETYPE_TRAVERSE, REST};

fn main() {
    let mut curves: BTreeMap<i32, BTreeMap<u32, [f32; 3]>> = BTreeMap::new();
    for path in std::env::args().skip(1) {
        for rec in open(&path).expect("open") {
            let rec = rec.expect("record");
            let q = &rec.player_out;
            let ty = u32_at(q, 0x26e8) as i32;
            if q[0x452] != MOVETYPE_TRAVERSE || u32_at(q, 0x26ec) != 0 || ty == REST || ty == JUMP_OFF {
                continue;
            }
            let Some(a) = lurch::oracle::RecordedRoot::of(&rec).at() else { continue };
            let r = vec3_at(q, 0x2724);
            let f = vec3_at(q, 0x2718);
            let yaw = (f[1] as f64).atan2(f[0] as f64);
            let (s, c) = yaw.sin_cos();
            let d = [(a[0] - r[0]) as f64, (a[1] - r[1]) as f64, (a[2] - r[2]) as f64];
            let local = [(c * d[0] + s * d[1]) as f32, (c * d[1] - s * d[0]) as f32, d[2] as f32];
            curves.entry(ty).or_default().insert(f32_at(q, 0x1eb4).to_bits(), local);
        }
    }
    println!("//! Generated by `cargo run --release --bin rootmotion traces/*.ltr`: the traversal");
    println!("//! animations' root motion as recordings show it. Rows are cycle, then the root's offset");
    println!("//! from the ledge point along the traversal's forward, its left and up.");
    println!();
    println!("pub static CURVES: &[(i32, &[[f32; 4]])] = &[");
    for (ty, rows) in &curves {
        println!("    ({ty}, &[");
        for (cycle, l) in rows {
            println!("        [{:?}, {:?}, {:?}, {:?}],", f32::from_bits(*cycle), l[0], l[1], l[2]);
        }
        println!("    ]),");
    }
    println!("];");
}
